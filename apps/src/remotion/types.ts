export type VideoLayerKind =
  | "background"
  | "pattern"
  | "icon"
  | "text"
  | "badge"
  | "media";

export interface VideoLayerSpec {
  id: string;
  trackCode: string;
  label: string;
  kind: VideoLayerKind;
  content?: string;
  color?: string;
  from: number;
  durationInFrames: number;
  visible: boolean;
  isCustom?: boolean;
}

export interface CustomVideoLayerInput {
  id: string;
  label: string;
  kind?: VideoLayerKind;
  content?: string;
  color?: string;
  from?: number;
  durationInFrames?: number;
  visible?: boolean;
}

export interface LayerOffset {
  x: number;
  y: number;
}

export const COLOR_HEX_MAP: Record<string, string> = {
  amber: "#F59E0B",
  orange: "#F97316",
  rose: "#F43F5E",
  pink: "#EC4899",
  fuchsia: "#D946EF",
  purple: "#A855F7",
  violet: "#7C3AED",
  indigo: "#6366F1",
  blue: "#3B82F6",
  sky: "#0EA5E9",
  cyan: "#06B6D4",
  blueprint: "#00E5FF",
  emerald: "#10B981",
  slate: "#64748B",
};

export function resolveColorToHex(input?: string, fallback = "#F97316"): string {
  if (!input) return fallback;
  const str = input.trim();
  if (str.startsWith("#")) {
    if (str.length === 4) {
      return `#${str[1]}${str[1]}${str[2]}${str[2]}${str[3]}${str[3]}`.toUpperCase();
    }
    return str.toUpperCase();
  }
  const lower = str.toLowerCase();
  if (COLOR_HEX_MAP[lower]) return COLOR_HEX_MAP[lower];
  return fallback;
}

export interface NexusVideoProps extends Record<string, unknown> {
  hookText: string;
  bodyText: string;
  authorHandle: string;
  themeColor: string;
  category: string;
  subCategory?: string;
  editorialTag?: string;
  showText?: boolean;
  showBackground?: boolean;
  isMuted?: boolean;
  /** Dynamic layers generated by LLM or added by user (unlimited V1..Vn tracks) */
  customLayers?: CustomVideoLayerInput[];
  /** Per-layer visibility map (keyed by layer id) */
  layerVisibility?: Record<string, boolean>;
  /** Per-layer start frame override (Premiere clip position) */
  layerStartFrame?: Record<string, number>;
  /** Per-layer duration override in frames (Premiere clip length) */
  layerDuration?: Record<string, number>;
  /** Optional custom label override for pattern/icon/background tracks */
  layerLabels?: Record<string, string>;
  /** Optional per-layer custom timeline color override (e.g. 'amber', 'rose', 'cyan') */
  layerColors?: Record<string, string>;
  /** Optional per-layer custom text font color override (e.g. '#ffffff', '#f59e0b') */
  layerTextColors?: Record<string, string>;
  /** Optional per-layer custom background color / style override */
  layerBgColors?: Record<string, string>;
  /** Composition video background style */
  bgStyle?: "radial" | "linear" | "vignette" | "solid" | "cyberpunk" | "blueprint";
  /** Per-layer manual position offsets { x: number, y: number } in composition pixels */
  layerOffsets?: Record<string, LayerOffset>;
  /** Visual effect controls for background & ambient pattern layers */
  orbSize?: number;
  orbBlur?: number;
  gridSize?: number;
  gridOpacity?: number;
  footerIconChar?: string;
}

