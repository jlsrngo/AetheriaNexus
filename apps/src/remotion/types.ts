export const nexusVideoSpec = {
  id: "NexusEditorialVideo",
  durationInFrames: 150,
  fps: 30,
  width: 1080,
  height: 1920,
} as const;

/**
 * Decomposes the video into individual Premiere-style NLE tracks so every
 * badge, text block, bullet point, icon, and background pattern has its own
 * independent <Sequence> clip.
 */
export function buildCompositionLayers(
  props: NexusVideoProps,
  totalFrames: number
): VideoLayerSpec[] {
  const vis = props.layerVisibility || {};
  const starts = props.layerStartFrame || {};
  const durations = props.layerDuration || {};
  const showBg = props.showBackground !== false;
  const showTxt = props.showText !== false;

  const isLayerVisible = (id: string, groupEnabled: boolean, defaultVis = true) =>
    groupEnabled && (vis[id] ?? defaultVis) !== false;

  const resolveTiming = (
    id: string,
    defaultFrom: number,
    defaultDur?: number
  ) => {
    const from = Math.max(
      0,
      Math.min(totalFrames - 5, Math.round(starts[id] ?? defaultFrom))
    );
    const maxDur = Math.max(5, totalFrames - from);
    const dur = Math.max(
      5,
      Math.min(maxDur, Math.round(durations[id] ?? defaultDur ?? maxDur))
    );
    return { from, durationInFrames: dur };
  };

  const bodyLines = (props.bodyText || "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);

  const customLayers = Array.isArray(props.customLayers)
    ? props.customLayers
    : [];

  const rawLayers: Array<Omit<VideoLayerSpec, "trackCode">> = [];

  // 1. Dynamic LLM / user custom layers (unlimited tracks)
  customLayers.forEach((custom, idx) => {
    const id = custom.id || `custom-layer-${idx}`;
    const defaultStart = Math.min(totalFrames - 15, custom.from ?? 12 + idx * 10);
    rawLayers.push({
      id,
      label: custom.label || `Custom Layer #${idx + 1}`,
      kind: custom.kind || "text",
      content: custom.content ?? custom.label,
      color: custom.color,
      ...resolveTiming(id, defaultStart, custom.durationInFrames),
      visible: isLayerVisible(id, showTxt, custom.visible ?? true),
      isCustom: true,
    });
  });

  // 2. Top HUD Category Badge (only created if category is non-empty)
  if ((props.category ?? "").trim().length > 0) {
    rawLayers.push({
      id: "hud-category",
      label: `Left Badge: // ${props.category}`,
      kind: "icon",
      ...resolveTiming("hud-category", 0),
      visible: isLayerVisible("hud-category", showTxt),
    });
  }

  // 3. Top HUD Subcategory Label (only created if subCategory is non-empty)
  if ((props.subCategory ?? "").trim().length > 0) {
    rawLayers.push({
      id: "hud-subcategory",
      label: `Right Label: [ ${props.subCategory} ]`,
      kind: "text",
      ...resolveTiming("hud-subcategory", 4),
      visible: isLayerVisible("hud-subcategory", showTxt),
    });
  }

  // 4. Main Hook Title (only created if hookText is non-empty)
  if ((props.hookText ?? "").trim().length > 0) {
    rawLayers.push({
      id: "text-hook",
      label: `Hook Title: "${props.hookText.slice(0, 24)}..."`,
      kind: "text",
      ...resolveTiming("text-hook", 8),
      visible: isLayerVisible("text-hook", showTxt),
    });
  }

  // 5. Dynamic Bullet Points (0 to N tracks depending on LLM output lines)
  bodyLines.forEach((line, idx) => {
    const id = `text-bullet-${idx}`;
    const defaultStart = Math.min(totalFrames - 15, 20 + idx * 14);
    rawLayers.push({
      id,
      label: `Point #${idx + 1}: ${line.slice(0, 26)}`,
      kind: "text",
      content: line,
      ...resolveTiming(id, defaultStart),
      visible: isLayerVisible(id, showTxt),
    });
  });

  // 6. Footer Avatar Icon & Author Handle (only created if authorHandle is non-empty)
  if ((props.authorHandle ?? "").trim().length > 0) {
    rawLayers.push({
      id: "footer-icon",
      label: "Avatar Icon: [⚡] Box",
      kind: "icon",
      ...resolveTiming("footer-icon", 32),
      visible: isLayerVisible("footer-icon", showTxt),
    });
    rawLayers.push({
      id: "footer-author",
      label: `Author: ${props.authorHandle}`,
      kind: "text",
      ...resolveTiming("footer-author", 36),
      visible: isLayerVisible("footer-author", showTxt),
    });
  }

  // 7. Footer Editorial Tag (only created if editorialTag is non-empty)
  if ((props.editorialTag ?? "").trim().length > 0) {
    rawLayers.push({
      id: "footer-tag",
      label: `Footer Badge: ${props.editorialTag}`,
      kind: "icon",
      ...resolveTiming("footer-tag", 40),
      visible: isLayerVisible("footer-tag", showTxt),
    });
  }

  // 8. Background Pattern & Gradient Layers
  rawLayers.push(
    {
      id: "bg-grid-pattern",
      label: "Pattern: Blueprint Grid",
      kind: "pattern",
      ...resolveTiming("bg-grid-pattern", 0),
      visible: isLayerVisible("bg-grid-pattern", showBg),
    },
    {
      id: "bg-orb-pattern",
      label: "Pattern: Ambient Glow Orb",
      kind: "pattern",
      ...resolveTiming("bg-orb-pattern", 0),
      visible: isLayerVisible("bg-orb-pattern", showBg),
    },
    {
      id: "bg-base",
      label: "Background: Radial Gradient",
      kind: "background",
      ...resolveTiming("bg-base", 0),
      visible: isLayerVisible("bg-base", showBg),
    }
  );

  const totalCount = rawLayers.length;
  return rawLayers.map((layer, index) => ({
    ...layer,
    trackCode: `V${totalCount - index}`,
  }));
}
